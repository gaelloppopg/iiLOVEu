// Función principal para traducir
export function t(key, lang) {
  const currentLang = lang || localStorage.getItem('idioma_global') || getBrowserLang();
  return translations[currentLang]?.[key] || translations['es'][key] || key;
}

// Detectar idioma del navegador
export function getBrowserLang() {
  const navLang = navigator.language || navigator.userLanguage;
  const code = navLang.split('-')[0].toLowerCase();
  if (translations[code]) return code;
  return 'es'; // Por defecto español
}

// Aplicar traducciones a los elementos con [data-i18n]
export function applyTranslations(lang) {
  const currentLang = lang || localStorage.getItem('idioma_global') || getBrowserLang();
  
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const texto = t(key, currentLang);
    // Permitir HTML en algunos textos
    if (texto.includes('<')) {
      el.innerHTML = texto;
    } else {
      el.textContent = texto;
    }
  });

  // Actualizar el atributo lang del HTML
  document.documentElement.lang = currentLang;
  // Si es árabe, aplicar dirección RTL
  if (currentLang === 'ar') {
    document.documentElement.dir = 'rtl';
  } else {
    document.documentElement.dir = 'ltr';
  }
}